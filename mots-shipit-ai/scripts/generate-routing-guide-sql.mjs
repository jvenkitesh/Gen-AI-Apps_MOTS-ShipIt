// Regenerates supabase/routing_guide.sql from data/Routing_Guide.json.
// Run from mots-shipit-ai/:  node scripts/generate-routing-guide-sql.mjs
// The generated seed upserts on (geography, origin_hub, zipcode, carrier, mode, weight_break):
// new carriers, ship-tos, modes, weight breaks, origin hubs or geographies are inserted as
// new rows; existing entries are updated in place. Rows removed from the JSON are NOT deleted.
// geography and origin_hub default to the file's top-level values; a row may override either.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const guide = JSON.parse(readFileSync(join(root, "data/Routing_Guide.json"), "utf8"));
const entries = guide.routes;

// Full name for each geography code. Add a row here (and run this script) before using a new code in the JSON.
const GEOGRAPHIES = [
  ["NA", "North America"],
  ["EMEA", "Europe"],
  ["APLA", "Pacific Asia"],
];

const columns = [
  "geography", "origin_hub", "state", "state_code", "gateway_city", "street_address", "zipcode", "corridor",
  "distance_miles", "transit_days", "mode", "transport", "carrier", "freight_cost_dollars", "weight_break",
];

const sqlValue = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

const valueRows = entries.map((entry) => {
  const row = {
    ...entry,
    geography: entry.geography ?? guide.geography,
    origin_hub: entry.origin_hub ?? guide.origin_hub,
  };
  return `  (${columns.map((c) => sqlValue(row[c])).join(", ")})`;
});

const countsByGeography = new Map();
for (const entry of entries) {
  const geo = entry.geography ?? guide.geography;
  countsByGeography.set(geo, (countsByGeography.get(geo) ?? 0) + 1);
}
const expectedCounts = [...countsByGeography.entries()];

const sql = `-- MOTS ShipIt -- Transportation and Shipment domain: routing guide
-- GENERATED by scripts/generate-routing-guide-sql.mjs from data/Routing_Guide.json -- do not edit by hand.
-- ${entries.length} entries. Safe to re-run: creation is idempotent, and the seed inserts new
-- entries and updates existing ones, matched on (geography, origin_hub, zipcode, carrier, mode, weight_break).

-- Runs as one transaction: if any step fails, nothing changes and existing routing guide records stay.
begin;

-- Geographies (Data Foundation): the code list routing_guide.geography must use.
create schema if not exists data_foundation;

create table if not exists data_foundation.geographies (
  code text primary key check (code ~ '^[A-Z]{2,6}$'),
  name text not null unique,
  created_at timestamptz not null default now()
);

comment on table data_foundation.geographies is
  'Geographies / marketplaces the organization operates in. code is the short code used on other tables (e.g. NA); name is the full name.';

alter table data_foundation.geographies enable row level security;

drop policy if exists "Signed-in users can read geographies" on data_foundation.geographies;
create policy "Signed-in users can read geographies"
  on data_foundation.geographies
  for select to authenticated
  using (true);

grant usage on schema data_foundation to authenticated, service_role;
grant select on data_foundation.geographies to authenticated;
grant all on data_foundation.geographies to service_role;

insert into data_foundation.geographies (code, name) values
${GEOGRAPHIES.map(([code, name]) => `  (${sqlValue(code)}, ${sqlValue(name)})`).join(",\n")}
on conflict (code) do update set name = excluded.name;

-- Routing guide (Transportation and Shipment)
create schema if not exists transportation_shipment;

create table if not exists transportation_shipment.routing_guide (
  id uuid primary key default gen_random_uuid(),
  geography text not null references data_foundation.geographies (code),
  origin_hub text not null,
  state text not null,
  state_code text not null check (char_length(state_code) = 2),
  gateway_city text not null,
  street_address text not null,
  zipcode text not null check (zipcode ~ '^[0-9]{5}$'),
  corridor text not null,
  distance_miles integer not null check (distance_miles > 0),
  transit_days integer not null check (transit_days >= 0),
  mode text not null check (mode in ('FTL', 'LTL', 'Intermodal')),
  transport text not null check (transport in ('Road', 'Rail')),
  carrier text not null,
  freight_cost_dollars numeric(10, 2) not null check (freight_cost_dollars >= 0),
  weight_break text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint routing_guide_entry_unique
    unique nulls not distinct (geography, origin_hub, zipcode, carrier, mode, weight_break)
);

-- Upgrade path for a routing_guide created before the geography column existed.
alter table transportation_shipment.routing_guide
  add column if not exists geography text references data_foundation.geographies (code);
update transportation_shipment.routing_guide set geography = ${sqlValue(guide.geography)} where geography is null;
alter table transportation_shipment.routing_guide alter column geography set not null;
alter table transportation_shipment.routing_guide drop constraint if exists routing_guide_entry_unique;
alter table transportation_shipment.routing_guide add constraint routing_guide_entry_unique
  unique nulls not distinct (geography, origin_hub, zipcode, carrier, mode, weight_break);
create index if not exists routing_guide_geography_idx on transportation_shipment.routing_guide (geography);

comment on table transportation_shipment.routing_guide is
  'Routing guide: for each geography and origin hub, the ship-to destinations, the carriers enabled for each, and weight breaks. freight_cost_dollars is kept here for this phase in place of a separate rate table.';
comment on column transportation_shipment.routing_guide.weight_break is
  'Weight band this entry applies to (e.g. <= 100 lbs). Null means the entry applies to all weights.';

create index if not exists routing_guide_zipcode_idx on transportation_shipment.routing_guide (zipcode);
create index if not exists routing_guide_state_code_idx on transportation_shipment.routing_guide (state_code);

alter table transportation_shipment.routing_guide enable row level security;

drop policy if exists "Signed-in users can read the routing guide" on transportation_shipment.routing_guide;
create policy "Signed-in users can read the routing guide"
  on transportation_shipment.routing_guide
  for select to authenticated
  using (true);

grant usage on schema transportation_shipment to authenticated, service_role;
grant select on transportation_shipment.routing_guide to authenticated;
grant all on transportation_shipment.routing_guide to service_role;

-- Seed from data/Routing_Guide.json
insert into transportation_shipment.routing_guide
  (${columns.join(", ")})
values
${valueRows.join(",\n")}
on conflict on constraint routing_guide_entry_unique do update set
  state = excluded.state,
  state_code = excluded.state_code,
  gateway_city = excluded.gateway_city,
  street_address = excluded.street_address,
  corridor = excluded.corridor,
  distance_miles = excluded.distance_miles,
  transit_days = excluded.transit_days,
  transport = excluded.transport,
  freight_cost_dollars = excluded.freight_cost_dollars,
  updated_at = now();

-- Safeguard: the knowledge base must hold at least every entry from the JSON for each geography in it.
do $$
declare
  expected record;
  actual integer;
begin
  for expected in
    select * from (values
${expectedCounts.map(([geo, n]) => `      (${sqlValue(geo)}, ${n})`).join(",\n")}
    ) as e (geography, entries)
  loop
    select count(*) into actual
      from transportation_shipment.routing_guide
      where geography = expected.geography;
    if actual < expected.entries then
      raise exception 'Routing guide for % has % entries, expected at least % -- rolling back', expected.geography, actual, expected.entries;
    end if;
  end loop;
end $$;

commit;
`;

writeFileSync(join(root, "supabase/routing_guide.sql"), sql);
console.log(`Wrote supabase/routing_guide.sql with ${entries.length} entries.`);
