// Regenerates supabase/routing_guide.sql from data/Routing_Guide.json.
// Run from mots-shipit-ai/:  node scripts/generate-routing-guide-sql.mjs
// The generated seed upserts on (origin_hub, zipcode, carrier, mode, weight_break):
// new carriers, ship-tos, modes, weight breaks or origin hubs are inserted as new rows;
// existing entries are updated in place. Rows removed from the JSON are NOT deleted.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const guide = JSON.parse(readFileSync(join(root, "data/Routing_Guide.json"), "utf8"));
const entries = guide.routes;

const columns = [
  "origin_hub", "state", "state_code", "gateway_city", "street_address", "zipcode", "corridor",
  "distance_miles", "transit_days", "mode", "transport", "carrier", "freight_cost_dollars", "weight_break",
];

const sqlValue = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

const valueRows = entries.map((entry) => {
  const row = { ...entry, origin_hub: entry.origin_hub ?? guide.origin_hub };
  return `  (${columns.map((c) => sqlValue(row[c])).join(", ")})`;
});

const sql = `-- MOTS ShipIt -- Transportation and Shipment domain: routing guide
-- GENERATED by scripts/generate-routing-guide-sql.mjs from data/Routing_Guide.json -- do not edit by hand.
-- ${entries.length} entries. Safe to re-run: creation is idempotent, and the seed inserts new
-- entries and updates existing ones, matched on (origin_hub, zipcode, carrier, mode, weight_break).

create schema if not exists transportation_shipment;

create table if not exists transportation_shipment.routing_guide (
  id uuid primary key default gen_random_uuid(),
  origin_hub text not null,
  state text not null,
  state_code text not null check (char_length(state_code) = 2),
  gateway_city text not null,
  street_address text not null,
  zipcode text not null check (zipcode ~ '^[0-9]{5}$'),
  corridor text not null,
  distance_miles integer not null check (distance_miles > 0),
  transit_days integer not null check (transit_days >= 0),
  mode text not null check (mode in ('FTL', 'LTL', 'Intermodal')),
  transport text not null check (transport in ('Road', 'Rail')),
  carrier text not null,
  freight_cost_dollars numeric(10, 2) not null check (freight_cost_dollars >= 0),
  weight_break text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint routing_guide_entry_unique
    unique nulls not distinct (origin_hub, zipcode, carrier, mode, weight_break)
);

comment on table transportation_shipment.routing_guide is
  'Routing guide: for each origin hub, the ship-to destinations, the carriers enabled for each, and weight breaks. freight_cost_dollars is kept here for this phase in place of a separate rate table.';
comment on column transportation_shipment.routing_guide.weight_break is
  'Weight band this entry applies to (e.g. <= 100 lbs). Null means the entry applies to all weights.';

create index if not exists routing_guide_zipcode_idx on transportation_shipment.routing_guide (zipcode);
create index if not exists routing_guide_state_code_idx on transportation_shipment.routing_guide (state_code);

alter table transportation_shipment.routing_guide enable row level security;

drop policy if exists "Signed-in users can read the routing guide" on transportation_shipment.routing_guide;
create policy "Signed-in users can read the routing guide"
  on transportation_shipment.routing_guide
  for select to authenticated
  using (true);

grant usage on schema transportation_shipment to authenticated, service_role;
grant select on transportation_shipment.routing_guide to authenticated;
grant all on transportation_shipment.routing_guide to service_role;

-- Seed from data/Routing_Guide.json
insert into transportation_shipment.routing_guide
  (${columns.join(", ")})
values
${valueRows.join(",\n")}
on conflict on constraint routing_guide_entry_unique do update set
  state = excluded.state,
  state_code = excluded.state_code,
  gateway_city = excluded.gateway_city,
  street_address = excluded.street_address,
  corridor = excluded.corridor,
  distance_miles = excluded.distance_miles,
  transit_days = excluded.transit_days,
  transport = excluded.transport,
  freight_cost_dollars = excluded.freight_cost_dollars,
  updated_at = now();
`;

writeFileSync(join(root, "supabase/routing_guide.sql"), sql);
console.log(`Wrote supabase/routing_guide.sql with ${entries.length} entries.`);
